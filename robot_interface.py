"""Real UR interface using RTDE. No MuJoCo or VAC equations live here.

Start from the robot's current stationary pose; no automatic moveJ is issued.
All Cartesian signals use the UR base frame. Set the robot's TCP and payload
before HIL; startup zeros F/T once. Only translational force enters VAC.
"""

import warnings
import time
import numpy as np

# Interface settings; students normally only edit config.py.
ORIENTATION_GAIN = 10.0
MAX_ANGULAR_SPEED = 0.3  # [rad/s]
ACCELERATION = 0.5      # speedL/speedStop acceleration parameter.


def rotation_matrix(rotvec):
    """Convert a UR rotation vector to a rotation matrix without SciPy."""
    angle = np.linalg.norm(rotvec)
    if angle < 1e-12:
        return np.eye(3)
    x, y, z = np.asarray(rotvec) / angle
    skew = np.array([[0, -z, y], [z, 0, -x], [-y, x, 0]])
    return np.eye(3) + np.sin(angle) * skew + (1 - np.cos(angle)) * (skew @ skew)


class RobotInterface:
    """Translate the shared demo interface into UR state reads and speedL.

    reference_position/reference_rotation are captured ONCE at startup.
    They are the fixed origin/orientation, not the time-varying nominal
    reference generated by reference_trajectory.py.
    """
    def __init__(self, config):
        # Imports are lazy: MuJoCo users do not need the RTDE package.
        from rtde_control import RTDEControlInterface
        from rtde_receive import RTDEReceiveInterface

        self.config = config
        self.control = self.receive = None
        self.period = None
        try:
            self.receive = RTDEReceiveInterface(config.robot_ip, 1.0 / config.dt)
            self.control = RTDEControlInterface(config.robot_ip, 1.0 / config.dt)
            self.refresh()
            if np.linalg.norm(self.receive.getActualTCPSpeed()) > 0.01:
                raise RuntimeError("Start the demo with the robot stationary")
            self.reference_position = self.position.copy()
            self.reference_rotation = self.rotation.copy()
            self.target = self.reference_position.copy()
        except BaseException:
            self.close()
            raise

    def refresh(self):
        """Read actual TCP state: position [m], linear velocity [m/s].

        UR pose entries 3:6 are a rotation vector, not Euler angles. Joint
        positions are in radians. None of these reads updates the VAC state.
        """
        if not self.receive.isConnected() or not self.control.isConnected():
            raise RuntimeError("RTDE connection lost")
        if self.receive.isProtectiveStopped() or self.receive.isEmergencyStopped():
            raise RuntimeError("Robot safety stop is active")
        pose = np.asarray(self.receive.getActualTCPPose(), dtype=float)
        self.position = pose[:3].copy()
        self.rotation = rotation_matrix(pose[3:])
        self.velocity = np.asarray(self.receive.getActualTCPSpeed(), dtype=float)[:3]
        self.joint_position = np.asarray(self.receive.getActualQ(), dtype=float)
        if not np.all(np.isfinite(np.r_[pose, self.joint_position, self.velocity])):
            raise RuntimeError("Nonfinite robot state")

    def zero_ft(self):
        """Zero once with the robot stationary and no external contact."""
        if not self.control.zeroFtSensor():
            raise RuntimeError("F/T zeroing failed; HIL was not started")
        time.sleep(0.1)  # Allow the receive stream to deliver post-zero samples.

    def read_force(self):
        """Read the base-frame TCP force."""
        return np.asarray(self.receive.getActualTCPForce(), dtype=float)[:3]

    def begin_cycle(self):
        """Start RTDE cycle timing and refresh state before computing a command."""
        self.period = self.control.initPeriod()
        self.refresh()

    def orientation_error(self):
        """Small-angle base-frame error used only to hold startup orientation."""
        return 0.5 * sum(
            (np.cross(self.rotation[:, j], self.reference_rotation[:, j])
             for j in range(3)), np.zeros(3)
        )

    def advance(self, target_position, target_velocity, dt):
        """Send one Cartesian velocity command for a control interval.

        target_position: absolute base-frame TCP target [m], used for
            bookkeeping and excursion checks, not position servoing.
        target_velocity: nominal + admittance linear velocity [m/s].
        dt: nominal interval [s], also used for the speedL time argument.

        There is no moveL/moveJ or translational position correction here.
        Consequently, target position and measured position can differ.
        """
        config = self.config
        self.target = np.asarray(target_position, dtype=float).copy()
        linear = target_velocity
        angular = ORIENTATION_GAIN * self.orientation_error()
        # speedL expects [vx, vy, vz, wx, wy, wz], in m/s and rad/s.
        # The last three entries hold orientation; they are not rotational VAC.
        command = np.r_[linear, angular]
        if not np.all(np.isfinite(command)):
            raise RuntimeError("Nonfinite Cartesian command")
        if max(np.linalg.norm(self.target - self.reference_position),
               np.linalg.norm(self.position - self.reference_position)) > config.max_displacement:
            raise RuntimeError("Robot TCP excursion limit exceeded")
        if (np.linalg.norm(linear) > config.max_speed
                or np.linalg.norm(angular) > MAX_ANGULAR_SPEED):
            raise RuntimeError("Robot Cartesian speed limit exceeded")
        # ACCELERATION is the interface's speed-ramp setting. It is distinct
        # from a_target, the model/reference acceleration plotted after a run.
        if not self.control.speedL(command.tolist(), ACCELERATION, dt):
            raise RuntimeError("Robot rejected the speedL command")
        self.control.waitPeriod(self.period)
        self.refresh()

    def close(self):
        """Attempt every cleanup operation, even if the connection has failed."""
        if self.control is not None:
            for operation in (
                lambda: self.control.speedStop(ACCELERATION),
                self.control.stopScript,
                self.control.disconnect,
            ):
                try:
                    operation()
                except Exception as error:
                    warnings.warn("RTDE shutdown: " + str(error))
            self.control = None
        if self.receive is not None:
            try:
                self.receive.disconnect()
            except Exception as error:
                warnings.warn("RTDE receive shutdown: " + str(error))
            self.receive = None
